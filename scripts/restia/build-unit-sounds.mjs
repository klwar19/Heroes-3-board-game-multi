#!/usr/bin/env node
/**
 * Writes src/restia/data/unit-sounds.ts: for every Restia monster sprite, which
 * Heroes 3 unit sounds (public/sounds/manifest.json "units/<name>-<kind>") exist.
 * Restia-only sprites borrow a similar creature's voice (ALIAS).
 *
 *   node scripts/restia/build-unit-sounds.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "public", "sounds", "manifest.json"), "utf8"));
const entries = manifest.sounds ?? manifest;
const ALIAS = { "restia-frost-wolf": "hell-hound", "restia-frost-rat": "goblin", "wolf-rider": "goblin-wolf-rider", argali: "mountain-ram" };
const KINDS = ["attack", "shoot", "hurt", "death"];

const source = fs.readFileSync(path.join(ROOT, "src", "restia", "data", "monsters.ts"), "utf8");
const sprites = [...new Set([...source.matchAll(/mon\("[^"]+", "[^"]+", "([^"]+)"/g)].map((match) => match[1]))].sort();
const out = {};
for (const sprite of sprites) {
  const voice = ALIAS[sprite] ?? sprite;
  // Only keys that live at /sounds/<key>.mp3 (the client builds the path from the key).
  const kinds = KINDS.filter((kind) => entries[`units/${voice}-${kind}`]?.src === `/sounds/units/${voice}-${kind}.mp3`);
  if (kinds.length) out[sprite] = { voice, kinds };
}
const body = Object.entries(out)
  .map(([sprite, { voice, kinds }]) => `  "${sprite}": { voice: "${voice}", kinds: [${kinds.map((kind) => `"${kind}"`).join(", ")}] }`)
  .join(",\n");
const file = `// Generated by scripts/restia/build-unit-sounds.mjs - do not edit by hand.
/** Monster sprite -> the Heroes 3 creature voice it uses and which sounds exist for it. */
export const UNIT_SOUNDS: Record<string, { voice: string; kinds: ("attack" | "shoot" | "hurt" | "death")[] }> = {
${body}
};

/** Sound key (public/sounds/<key>.mp3) for a monster action, falling back from shoot to attack. */
export function unitSound(sprite: string, kind: "attack" | "shoot" | "hurt" | "death"): string | undefined {
  const entry = UNIT_SOUNDS[sprite];
  if (!entry) return undefined;
  const pick = entry.kinds.includes(kind) ? kind : kind === "shoot" && entry.kinds.includes("attack") ? "attack" : null;
  return pick ? \`units/\${entry.voice}-\${pick}\` : undefined;
}
`;
fs.writeFileSync(path.join(ROOT, "src", "restia", "data", "unit-sounds.ts"), file);
console.log(`unit-sounds: ${Object.keys(out).length}/${sprites.length} sprites voiced`);
